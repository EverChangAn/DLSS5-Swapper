let current = 'en';

function setLang(code) {
  current = S[code] ? code : 'en';
  return current;
}

const getLang = () => current;
const dirOf = (code) => (LANGS.find((l) => l.code === (code || current)) || LANGS[0]).dir;

// Missing keys fall back to English rather than showing a blank.
function t(key, ...args) {
  const entry = S[current][key] !== undefined ? S[current][key] : S.en[key];
  if (entry === undefined) return String(key);
  return typeof entry === 'function' ? entry(...args) : entry;
}

// Extra languages register themselves rather than bloating this file.
function add(meta, strings) {
  if (!S[meta.code]) LANGS.push(meta);
  S[meta.code] = strings;
}

window.i18n = { t, setLang, getLang, dirOf, LANGS, S, add };
